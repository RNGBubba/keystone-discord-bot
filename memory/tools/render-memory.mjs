#!/usr/bin/env node
/**
 * `pnpm memory:render` — generate the human half from the machine half.
 *
 * The generated pages are deliberately plain Markdown with wikilinks, so they
 * render in Obsidian, on GitHub and in a text editor. `memory:check` recomputes
 * them and fails when they are stale, which is what stops a status page from
 * quietly disagreeing with `features.json`.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const memoryDir = path.join(root, "memory");

const HEADER = "<!-- generated by pnpm memory:render; do not edit by hand -->";

async function readJson(relative) {
  return JSON.parse(await readFile(path.join(memoryDir, relative), "utf8"));
}

const STATUS = {
  "shipped-in-repo": "✅ in repo",
  open: "◐ open",
  planned: "⏳ planned",
  "non-goal": "— non-goal",
};

function cell(value) {
  return String(value ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function featureRows(domain) {
  return domain.features.map((feature) => {
    const status = STATUS[feature.status] ?? feature.status;
    const live = feature.status === "shipped-in-repo" && feature.liveVerified === false
      ? "live unverified"
      : feature.liveVerified === true
        ? "live verified"
        : "";
    const evidence = (feature.evidence ?? []).map((entry) => `\`${entry}\``).join(", ");
    const detail = [feature.openReason, evidence, live].filter(Boolean).join(" · ");
    return `| ${cell(feature.name)} | ${cell(feature.phase)} | ${cell(status)} | ${cell(detail || feature.note)} |`;
  });
}

export async function renderAll() {
  const project = await readJson("machine/project.json");
  const features = await readJson("machine/features.json");
  const research = await readJson("machine/research.json");
  const passes = await readJson("machine/passes.json");
  const decisions = await readJson("machine/decisions.json");
  const live = await readJson("machine/live.json");

  const total = features.domains.reduce((sum, domain) => sum + domain.features.length, 0);
  const shipped = features.domains.reduce(
    (sum, domain) => sum + domain.features.filter((feature) => feature.status === "shipped-in-repo").length,
    0,
  );
  const open = features.domains.reduce(
    (sum, domain) => sum + domain.features.filter((feature) => feature.status === "open").length,
    0,
  );
  const planned = features.domains.reduce(
    (sum, domain) => sum + domain.features.filter((feature) => feature.status === "planned").length,
    0,
  );

  const featurePage = [
    HEADER,
    "",
    "# Feature status",
    "",
    "> Machine truth: [`features.json`](../../machine/features.json). This page is generated.",
    "> The competitor columns stay in [[Parity-Matrix]]; this page is the implementation status.",
    "",
    `**${total} features** across ${features.domains.length} domains: **${shipped} in repo**, ` +
      `**${open} open**, **${planned} planned**. Live behaviour is marked separately; a green`,
    "box means the code and its tests exist, not that a live guild has run it.",
    "",
    "## Domains",
    "",
    "| Domain | Features | In repo | Open | Planned |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...features.domains.map((domain) => {
      const count = (status) => domain.features.filter((feature) => feature.status === status).length;
      return `| ${cell(domain.name)} | ${domain.features.length} | ${count("shipped-in-repo")} | ${count("open")} | ${count("planned")} |`;
    }),
    "",
    ...features.domains.flatMap((domain) => [
      `## ${domain.name}`,
      "",
      "| Feature | Phase | Status | Evidence / note |",
      "| --- | --- | --- | --- |",
      ...featureRows(domain),
      "",
    ]),
    "## How to change this page",
      "",
      "1. Edit [`features.json`](../../machine/features.json), not this file.",
      "2. Run `pnpm memory:render`.",
      "3. Run `pnpm memory:check`.",
      "4. A `shipped-in-repo` row needs an `evidence` path; a `verified` row needs a live proof.",
    "",
  ].join("\n");

  const claimPage = [
    HEADER,
    "",
    "# Research claims",
    "",
    "> Machine truth: [`research.json`](../../machine/research.json). This page is generated.",
    "> Every claim has a source, a retrieval date, a confidence and an expiry. A claim older",
    "> than two quarters is a rumour: refresh it or mark it stale before using it in copy.",
    "",
    "| ID | Topic | Claim | Confidence | Source | Retrieved | Expires |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...research.claims.map(
      (claim) =>
        `| ${cell(claim.id)} | ${cell(claim.topic)} | ${cell(claim.claim)} | ${cell(claim.confidence)} | [source](${claim.source}) | ${cell(claim.retrievedAt)} | ${cell(claim.expiresAt)} |`,
    ),
    "",
    "## Rules",
    "",
    "- Snippet-only claims are `confidence: low` or `medium` and never appear in marketing copy.",
    "- A price from a third-party comparison is `medium` unless an official page was read.",
    "- Expired claims fail `pnpm memory:check`; refresh the source, do not extend the date.",
    "",
  ].join("\n");

  const decisionPage = [
    HEADER,
    "",
    "# Decision index",
    "",
    "> Machine truth: [`decisions.json`](../../machine/decisions.json). This page is generated.",
    "> The prose reasoning lives in each ADR; the audit trail lives in [[Decision-Log]].",
    "",
    "| ID | Decision | Status | Date |",
    "| --- | --- | --- | --- |",
    ...decisions.decisions.map(
      (decision) =>
        `| ${cell(decision.id)} | [[${path.basename(decision.path, ".md")}\\|${cell(decision.title)}]] | ${cell(decision.status)} | ${cell(decision.date)} |`,
    ),
    "",
    "## Rules",
    "",
    "- A contract change needs an ADR with **Status** and **Alternatives**.",
    "- A superseded ADR stays; do not delete the history.",
    "",
  ].join("\n");

  const passPage = [
    HEADER,
    "",
    "# Pass ledger",
    "",
    "> Machine truth: [`passes.json`](../../machine/passes.json). This page is generated.",
    "> Every pass links to a journal with what changed, what was rejected, verification and next.",
    "",
    "| Pass | Date | Phase | Summary | Journal |",
    "| --- | --- | --- | --- | --- |",
    ...passes.passes
      .slice()
      .reverse()
      .map(
        (pass) =>
          `| ${cell(pass.id)} | ${cell(pass.date)} | ${cell(pass.phase)} | ${cell(pass.summary)} | [journal](../../${pass.journal}) |`,
      ),
    "",
    `Current phase: **${project.phase}**. ${project.metrics?.tests ?? "?"} tests reported; ` +
      `${project.metrics?.commands ?? "?"}/${project.metrics?.commandLimit ?? 100} global roots` +
      `${project.metrics?.subcommands ? " (" + project.metrics.subcommands + " subcommands)" : ""}.`,
    "",
  ].join("\n");

  const livePage = [
    HEADER,
    "",
    "# Live window",
    "",
    "> Machine truth: [`live.json`](../../machine/live.json). This page is generated.",
    "> A passing local suite does not prove a service; this page records the last",
    "> `pnpm probe:live` run against the configured Postgres and Redis.",
    "",
    `Last probe: **${cell(live.date)}** (\`${cell(live.id)}\`), generated ${cell(live.generatedAt)}.`,
    "",
    "| Service | Result |",
    "| --- | --- |",
    `| Docker | ${live.docker?.running ? `server ${cell(live.docker.version)}` : "not reachable"} |`,
    `| Postgres | ${live.services?.postgres?.reachable ? `${cell(live.services.postgres.version)} · ${live.services.postgres.migrations?.applied ?? "?"} migrations · ${live.services.postgres.migrations?.pending ?? "?"} pending` : "not reachable"} |`,
    `| Redis | ${live.services?.redis?.reachable ? "reachable" : "not reachable"} |`,
    "",
    "## Checks",
    "",
    "| Check | Status | Evidence | Features |",
    "| --- | --- | --- | --- |",
    ...live.checks.map(
      (check) =>
        `| ${cell(check.id)} | ${cell(check.status)} | ${cell(check.detail)} | ${cell((check.features ?? []).join(", "))} |`,
    ),
    "",
    "## Rules",
    "",
    "- This probe is not part of `pnpm check`; the gate must pass without a database.",
    "- A feature may set `liveVerified: true` only when its row names a passing",
    "  `liveEvidence` check from this report.",
    "- Re-run `pnpm probe:live` after changing a SQL, Redis, queue or web path.",
    "",
  ].join("\n");

  return new Map([
    ["vault/01-Mission/Feature-Status.md", featurePage],
    ["vault/02-Research/Claims.md", claimPage],
    ["vault/99-Meta/Decision-Index.md", decisionPage],
    ["vault/05-Learning/Pass-Ledger.md", passPage],
    ["vault/06-Operations/Live-Window.md", livePage],
  ]);
}

async function main() {
  const dryRun = process.argv.includes("--check");
  const pages = await renderAll();
  let stale = 0;

  for (const [relative, content] of pages) {
    const file = path.join(memoryDir, relative);
    if (dryRun) {
      let existing = "";
      try {
        existing = await readFile(file, "utf8");
      } catch {
        existing = "";
      }
      if (existing !== content) {
        stale += 1;
        console.error(`memory: stale ${relative} — run pnpm memory:render`);
      }
      continue;
    }
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content, "utf8");
    console.log(`memory: wrote ${relative}`);
  }

  if (dryRun) {
    if (stale > 0) process.exitCode = 1;
    else console.log("memory: generated pages are current");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  main().catch((error) => {
    console.error("memory:render crashed:", error);
    process.exit(1);
  });
}
